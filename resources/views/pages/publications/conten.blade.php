<!-- ==========================================================
     INTERACTIVE JAVASCRIPT: FILTER, SORT, MODAL
     ========================================================== -->
<script>
document.addEventListener('DOMContentLoaded', function() {
    const yearBtns = document.querySelectorAll('.year-nav-btn');
    const catBtns = document.querySelectorAll('.cat-filter-btn');
    const yearSections = document.querySelectorAll('.year-group-section');
    const pubCountTitle = document.getElementById('pubCountTitle');
    const pubEmptyState = document.getElementById('pubEmptyState');
    const emptyResetBtn = document.getElementById('emptyResetBtn');
    const pubSortSelect = document.getElementById('pubSortSelect');

    const totalPapers = document.querySelectorAll('.paper-card').length;

    let selectedYear = 'all';
    let selectedCategory = 'all';

    // Combined Year & Category Filter Handling
    function applyCombinedFilter() {
        let totalVisible = 0;

        yearSections.forEach(section => {
            const groupYear = section.getAttribute('data-group-year');
            const yearMatches = (selectedYear === 'all' || groupYear === selectedYear);
            const cards = section.querySelectorAll('.paper-card');
            let visibleInYear = 0;

            cards.forEach(card => {
                const cardCat = card.getAttribute('data-category') || 'others';
                const catMatches = (selectedCategory === 'all' || cardCat === selectedCategory);

                if (yearMatches && catMatches) {
                    card.style.display = 'flex';
                    visibleInYear++;
                    totalVisible++;
                } else {
                    card.style.display = 'none';
                }
            });

            // Show section header if at least one card is visible
            if (visibleInYear > 0) {
                section.style.display = 'flex';
                const qtySpan = section.querySelector('.year-qty');
                if (qtySpan) qtySpan.textContent = `(${visibleInYear})`;
            } else {
                section.style.display = 'none';
            }
        });

        // Update count title
        let activeCatBtn = document.querySelector('.cat-filter-btn.active .cat-name');
        let catText = activeCatBtn ? activeCatBtn.textContent : 'Semua Kategori';

        if (selectedYear === 'all' && selectedCategory === 'all') {
            pubCountTitle.textContent = `Semua Publikasi (${totalPapers})`;
        } else if (selectedYear !== 'all' && selectedCategory === 'all') {
            pubCountTitle.textContent = `Publikasi ${selectedYear} (${totalVisible})`;
        } else if (selectedYear === 'all' && selectedCategory !== 'all') {
            pubCountTitle.textContent = `${catText} (${totalVisible})`;
        } else {
            pubCountTitle.textContent = `${selectedYear} • ${catText} (${totalVisible})`;
        }

        // Show/hide empty state
        if (pubEmptyState) {
            pubEmptyState.style.display = (totalVisible === 0) ? 'block' : 'none';
        }
    }

    // 1. Year Filter Event
    yearBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            yearBtns.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
            selectedYear = this.getAttribute('data-year') || 'all';
            applyCombinedFilter();
        });
    });

    // 2. Category Filter Event
    catBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            catBtns.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
            selectedCategory = this.getAttribute('data-cat') || 'all';
            applyCombinedFilter();
        });
    });

    // Reset Filter Button in Empty State
    if (emptyResetBtn) {
        emptyResetBtn.addEventListener('click', function() {
            const allYearBtn = document.querySelector('.year-nav-btn[data-year="all"]');
            const allCatBtn = document.querySelector('.cat-filter-btn[data-cat="all"]');
            if (allYearBtn) {
                yearBtns.forEach(b => b.classList.remove('active'));
                allYearBtn.classList.add('active');
                selectedYear = 'all';
            }
            if (allCatBtn) {
                catBtns.forEach(b => b.classList.remove('active'));
                allCatBtn.classList.add('active');
                selectedCategory = 'all';
            }
            applyCombinedFilter();
        });
    });

    // 2. Sort Select Handling
    if (pubSortSelect) {
        pubSortSelect.addEventListener('change', function() {
            const sortMode = this.value;
            yearSections.forEach(section => {
                const grid = section.querySelector('.cards-grid');
                if (!grid) return;
                const cards = Array.from(grid.querySelectorAll('.paper-card'));

                cards.sort((a, b) => {
                    const titleA = a.getAttribute('data-title') || '';
                    const titleB = b.getAttribute('data-title') || '';
                    const dateA = a.querySelector('.meta-date-item')?.textContent || '';
                    const dateB = b.querySelector('.meta-date-item')?.textContent || '';

                    if (sortMode === 'az') {
                        return titleA.localeCompare(titleB);
                    } else if (sortMode === 'oldest') {
                        return dateA.localeCompare(dateB);
                    } else {
                        // Newest First (default layout order)
                        return 0;
                    }
                });

                cards.forEach(card => grid.appendChild(card));
            });
        });
    }

    // 3. Interactive Paper Detail Modal (100% Persis User Reference)
    const paperModal = document.getElementById('paperModal');
    const modalCloseBtn = document.getElementById('modalCloseBtn');
    const modalPaperTitle = document.getElementById('modalPaperTitle');
    const modalAuthorPills = document.getElementById('modalAuthorPills');
    const modalVenueFull = document.getElementById('modalVenueFull');
    const modalVenueLocation = document.getElementById('modalVenueLocation');
    const modalYearVal = document.getElementById('modalYearVal');
    const modalYearSide = document.getElementById('modalYearSide');
    const modalDoiVal = document.getElementById('modalDoiVal');
    const modalCitationText = document.getElementById('modalCitationText');
    const modalKeywordsWrap = document.getElementById('modalKeywordsWrap');

    const openTriggers = document.querySelectorAll('.open-paper-modal, .view-paper-btn');
    openTriggers.forEach(trigger => {
        trigger.addEventListener('click', function(e) {
            e.preventDefault();
            e.stopPropagation();

            const title = this.getAttribute('data-title') || 'Hybrid Intrusion Detection System Using Machine Learning';
            const authors = this.getAttribute('data-authors') || 'Dwi Okta Suryaningrum, Rio Adi Setiono, dkk.';
            const venue = this.getAttribute('data-venue') || 'International Conference on Computer and Information Sciences (IC-COINS)';
            const date = this.getAttribute('data-date') || '2026';
            const topic = this.getAttribute('data-topic') || 'Network Security';

            // 1. Title & Year
            if (modalPaperTitle) modalPaperTitle.textContent = title;
            const yearNum = date.includes(' ') ? date.split(' ')[1] : date;
            if (modalYearVal) modalYearVal.textContent = yearNum;
            if (modalYearSide) modalYearSide.textContent = yearNum;

            // 2. Venue & Location
            const venueClean = venue.replace(/•/g, '-');
            if (modalVenueFull) modalVenueFull.textContent = venueClean;
            if (modalVenueLocation) modalVenueLocation.textContent = `Bandung, Indonesia • ${date}`;

            // 3. Dynamic Author Pills with Superscripts
            if (modalAuthorPills) {
                const authorsArr = authors.split(',').map(a => a.trim().replace(/^and\s+/i, '')).filter(Boolean);
                modalAuthorPills.innerHTML = authorsArr.map((author, idx) => {
                    const sup = (idx === 1) ? '1, 2' : '1';
                    return `<span class="author-pill">${author} <sup>${sup}</sup></span>`;
                }).join(' ');
            }

            // 4. Keywords
            if (modalKeywordsWrap) {
                const topicTags = [topic, 'Cybersecurity', 'Machine Learning', 'Network Security', 'Ensemble Classifiers'];
                modalKeywordsWrap.innerHTML = topicTags.map(tag => `<span class="keyword-pill">${tag}</span>`).join(' ');
            }

            // 5. DOI & Citation Text
            const cleanDoiSuffix = title.toLowerCase().replace(/[^a-z0-9]/g, '').substring(0, 10);
            const doiStr = `10.1016/j.nev.${yearNum}.${cleanDoiSuffix}`;
            if (modalDoiVal) modalDoiVal.textContent = doiStr;

            if (modalCitationText) {
                const authorLead = authors.split(',')[0].trim();
                const venueShort = venue.split('•')[0].trim();
                modalCitationText.textContent = `${authorLead} et al., "${title}," ${venueShort}, ${date}. DOI: ${doiStr}.`;
            }

            // Open Modal
            if (paperModal) {
                paperModal.style.display = 'flex';
                document.body.style.overflow = 'hidden';
            }
        });
    });

    // Close Modal Functions
    function closePaperModal() {
        if (paperModal) {
            paperModal.style.display = 'none';
            document.body.style.overflow = '';
        }
    }

    if (modalCloseBtn) modalCloseBtn.addEventListener('click', closePaperModal);
    if (paperModal) {
        paperModal.addEventListener('click', function(e) {
            if (e.target === paperModal) closePaperModal();
        });
    }
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape' && paperModal && paperModal.style.display === 'flex') {
            closePaperModal();
        }
    });

    // Tab Switching in Detail Modal
    const tabBtns = document.querySelectorAll('.detail-tab-btn');
    const tabPanes = document.querySelectorAll('.detail-tab-pane');
    tabBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            tabBtns.forEach(b => b.classList.remove('active'));
            tabPanes.forEach(p => {
                p.classList.remove('active');
                p.style.display = 'none';
            });

            this.classList.add('active');
            const targetId = this.getAttribute('data-tab');
            const targetPane = document.getElementById(targetId);
            if (targetPane) {
                targetPane.classList.add('active');
                targetPane.style.display = 'block';
            }
        });
    });

    // Copy Citation Button
    const copyCitationBtn = document.getElementById('copyCitationBtn');
    const copyBtnText = document.getElementById('copyBtnText');
    if (copyCitationBtn && modalCitationText) {
        copyCitationBtn.addEventListener('click', function() {
            navigator.clipboard.writeText(modalCitationText.textContent.trim()).then(() => {
                if (copyBtnText) copyBtnText.textContent = '✓ Sitasi Tersalin!';
                copyCitationBtn.style.background = '#065f46';
                setTimeout(() => {
                    if (copyBtnText) copyBtnText.textContent = 'Salin Sitasi';
                    copyCitationBtn.style.background = '';
                }, 2000);
            });
        });
    }

    // Copy DOI Row
    const doiBtn = document.getElementById('doiRecordBtn');
    if (doiBtn && modalDoiVal) {
        doiBtn.addEventListener('click', function() {
            navigator.clipboard.writeText(modalDoiVal.textContent.trim()).then(() => {
                alert('DOI berhasil disalin: ' + modalDoiVal.textContent.trim());
            });
        });
